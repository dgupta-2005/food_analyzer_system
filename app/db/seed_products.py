async def seed_products():
    """Seeds popular English foods into the database catalog."""
    async with AsyncSessionLocal() as db:
        added_count = 0
        for item in CURATED_PRODUCTS:
            stmt = select(PackagedProduct).where(
                (PackagedProduct.barcode == item["barcode"]) | 
                (PackagedProduct.product_name == item["product_name"])
            )
            res = await db.execute(stmt)
            existing = res.scalar_one_or_none()
            if not existing:
                db.add(PackagedProduct(**item))
                added_count += 1
        if added_count > 0:
            await db.commit()
            print(f"[OK] Seeded {added_count} curated English food products into local database.")
        else:
            print("[INFO] Curated food products already exist in database.")

if __name__ == "__main__":
    asyncio.run(seed_products())
